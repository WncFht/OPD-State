"""Validation token preservation, distributed scoring and explicit KL metrics."""

from __future__ import annotations

import hashlib
import json
import math
import time
from collections import defaultdict
from pathlib import Path

import numpy as np
import torch

from verl import DataProto
from verl.protocol import pad_dataproto_to_divisor, unpad_dataproto
from verl.workers.validation_kl import STATISTICS, record_fingerprint, validate_record


def validate_settings(config, *, native_enabled):
    settings = config.trainer.get("validation_kl", {})
    if not settings.get("enabled", False):
        return
    if not native_enabled or not config.distillation.fsdp_teacher.enabled:
        raise ValueError("Validation KL requires native rollout and the colocated FSDP teacher")
    if config.distillation.fsdp_teacher.get("teachers"):
        raise ValueError("Validation KL currently requires one frozen teacher")
    if config.actor_rollout_ref.model.get("use_fused_kernels", False):
        raise ValueError("Validation KL requires unfused causal-model forwards")
    if not config.trainer.get("validation_data_dir"):
        raise ValueError("Validation KL requires validation_data_dir for token and score evidence")
    for name in ("position_chunk_size", "vocab_chunk_size"):
        value = settings.get(name)
        if type(value) is not int or value < 1:
            raise ValueError(f"Validation KL {name} must be a positive integer")


def collect_records(batch, *, student_version):
    """Preserve compact raw tokens after DP unpadding, without re-tokenizing text."""
    prompt_width = batch.batch["prompts"].shape[-1]
    lengths = batch.batch["response_mask"].sum(-1).cpu().tolist()
    records = []
    for i, length in enumerate(lengths):
        prompt_mask = batch.batch["attention_mask"][i, :prompt_width].bool()
        info = batch.non_tensor_batch["native_response_info"][i]
        if info["student_version"] != student_version:
            raise ValueError("Validation KL input was generated by a different student version")
        records.append(
            {
                "state_source": "on_validation_states",
                "source": str(batch.non_tensor_batch["data_source"][i]),
                "uid": str(batch.non_tensor_batch["uid"][i]),
                "sample": int(info["sample"]),
                "prompt_ids": batch.batch["prompts"][i, prompt_mask].cpu().tolist(),
                "response_ids": batch.batch["responses"][i, : int(length)].cpu().tolist(),
            }
        )
    return records


def load_fixed_bank(path, config, tokenizer):
    """Bind an optional immutable p0/q bank to tokenizer and frozen model identities."""
    if not path:
        return [], None
    from verl.trainer.ppo.fixed_rollout import model_signature, tokenizer_signature

    raw = Path(path).read_bytes()
    bank = json.loads(raw)
    expected = {
        "schema": "fixed-prefix-bank-v1",
        "vocab_size": len(tokenizer),
        "tokenizer_signature": tokenizer_signature(tokenizer),
        "initial_student_fingerprint": model_signature(config.actor_rollout_ref.model.path),
        "teacher_fingerprint": model_signature(config.distillation.fsdp_teacher.model_path),
    }
    if any(bank.get(key) != value for key, value in expected.items()):
        raise ValueError("Fixed prefix bank tokenizer/vocabulary/model identity does not match this experiment")
    records = bank.get("records", [])
    if {row.get("state_source") for row in records} != {"on_initial_states", "on_teacher_states"}:
        raise ValueError("Fixed prefix bank must contain initial-student and teacher states")
    keys = set()
    questions = defaultdict(dict)
    for row in records:
        validate_record(row, len(tokenizer))
        if tokenizer.eos_token_id in row["response_ids"][:-1]:
            raise ValueError("Fixed prefix bank response continued after EOS")
        key = row["state_source"], row["source"], row["uid"], row["sample"]
        if key in keys:
            raise ValueError("Fixed prefix bank contains duplicate responses")
        keys.add(key)
        prompt_key = row["source"], row["uid"]
        questions[row["state_source"]][prompt_key] = tuple(row["prompt_ids"])
    if questions["on_initial_states"] != questions["on_teacher_states"]:
        raise ValueError("Fixed prefix bank sources must use identical question IDs and raw prompts")
    return records, hashlib.sha256(raw).hexdigest()


def summarize_kl(rows):
    """Keep token weighting, per-question weighting and cumulative mismatch separate."""
    groups = defaultdict(list)
    seen = set()
    for row in rows:
        key = row["state_source"], row["source"], row["uid"], row["sample"]
        if key in seen or row["source"] in {"micro", "macro"}:
            raise ValueError("KL response identities must be unique and benchmark names unreserved")
        seen.add(key)
        if row["response_length"] < 1 or any(not math.isfinite(value) for value in row["sums"].values()):
            raise ValueError("KL response lengths and statistics must be valid and finite")
        groups[row["state_source"], row["source"]].append(row)
    metrics = {}

    def record(state_source, source, values):
        prefix = f"validation_kl/{state_source}/{source}/"
        total_tokens = sum(row["response_length"] for row in values)
        questions = defaultdict(list)
        for row in values:
            questions[row["source"], row["uid"]].append(row)
        out = {
            "responses": len(values),
            "questions": len(questions),
            "response_tokens": total_tokens,
            "evaluated_positions": sum(row["evaluated_positions"] for row in values),
        }
        for name in STATISTICS:
            out[name + "/token_weighted"] = math.fsum(row["sums"][name] for row in values) / total_tokens
            out[name + "/question_mean"] = math.fsum(
                math.fsum(row["sums"][name] / row["response_length"] for row in items) / len(items)
                for items in questions.values()
            ) / len(questions)
            out[name + "/cumulative_on_states"] = math.fsum(
                math.fsum(row["sums"][name] for row in items) / len(items) for items in questions.values()
            ) / len(questions)
        for depth in ("0_255", "256_1023", "1024_2047", "2048_plus"):
            parts = [row.get("depths", {}).get(depth) for row in values]
            parts = [part for part in parts if part is not None]
            count = sum(part["tokens"] for part in parts)
            out[f"depth/{depth}/tokens"] = count
            if count:
                for name in STATISTICS:
                    out[f"depth/{depth}/{name}/token_weighted"] = (
                        math.fsum(part["sums"][name] for part in parts) / count
                    )
        metrics.update({prefix + key: value for key, value in out.items()})

    for (state_source, source), values in sorted(groups.items()):
        record(state_source, source, values)
    for state_source in sorted({state for state, _ in groups}):
        sources = [source for state, source in groups if state == state_source]
        record(state_source, "micro", [row for row in rows if row["state_source"] == state_source])
        for name in STATISTICS:
            for reduction in ("question_mean", "token_weighted", "cumulative_on_states"):
                key = name + "/" + reduction
                metrics[f"validation_kl/{state_source}/macro/{key}"] = math.fsum(
                    metrics[f"validation_kl/{state_source}/{source}/{key}"] for source in sources
                ) / len(sources)
    return metrics


def run_validation_kl(trainer, records):
    """Score before final weights disappear; all generation replicas must sleep first."""
    settings = trainer.config.trainer.validation_kl
    bank, bank_sha = getattr(trainer, "_validation_kl_bank", ([], None))
    all_records = records + bank
    if not records:
        raise ValueError("Validation KL requires the complete validation response set")
    for row in all_records:
        validate_record(row, len(trainer.tokenizer))
    non_tensors = np.empty(len(all_records), dtype=object)
    for index, row in enumerate(all_records):
        non_tensors[index] = row
    data = DataProto.from_dict(
        tensors={"validation_row_id": torch.arange(len(all_records))},
        non_tensors={"validation_kl_records": non_tensors},
        meta_info={
            "student_version": trainer.global_steps,
            "vocab_size": len(trainer.tokenizer),
            "position_chunk_size": int(settings.position_chunk_size),
            "vocab_chunk_size": int(settings.vocab_chunk_size),
        },
    )
    padded, pad = pad_dataproto_to_divisor(data, int(trainer.opd_teacher_wg.world_size))
    tick = time.perf_counter()
    trainer.rollout_coordinator.sleep_replicas()
    sleep_seconds = time.perf_counter() - tick
    tick = time.perf_counter()
    score_started = time.time()
    output = trainer.opd_teacher_wg.compute_validation_kl(padded)
    elapsed = time.perf_counter() - tick
    score_finished = time.time()
    output = unpad_dataproto(output, pad)
    if not torch.equal(output.batch["validation_row_id"].cpu(), data.batch["validation_row_id"]):
        raise ValueError("Validation KL worker changed response order or cardinality")
    if output.meta_info.get("student_version") != trainer.global_steps:
        raise ValueError("Validation KL worker returned the wrong student version")
    rows = output.non_tensor_batch["validation_kl_stats"].tolist()
    for raw, scored in zip(all_records, rows, strict=True):
        if scored["record_sha256"] != record_fingerprint(raw) or scored["response_length"] != len(raw["response_ids"]):
            raise ValueError("Validation KL worker scored different tokens or response identities")
        if raw["state_source"] == "on_validation_states" and scored["evaluated_positions"] != len(raw["response_ids"]):
            raise ValueError("Validation KL worker skipped effective validation positions")
    metrics = summarize_kl(rows)
    metrics["validation_kl/performance/scoring_seconds"] = elapsed
    metrics["validation_kl/performance/rollout_sleep_seconds"] = sleep_seconds
    # The accuracy collector interprets every top-level *.jsonl stem as a step.
    # Diagnostic token records must not enter that namespace.
    directory = Path(trainer.config.trainer.validation_data_dir) / "kl"
    directory.mkdir(parents=True, exist_ok=True)
    token_path = directory / f"kl-tokens-step-{trainer.global_steps}.jsonl"
    token_digest = hashlib.sha256()
    with token_path.open("x") as stream:
        for row in all_records:
            line = json.dumps(row, separators=(",", ":")) + "\n"
            stream.write(line)
            token_digest.update(line.encode())
    generation = trainer.config.actor_rollout_ref.rollout.val_kwargs
    report = {
        "schema": "validation-kl-v1",
        "student_version": trainer.global_steps,
        "scoring_temperature": 1,
        "effective_vocab_size": len(trainer.tokenizer),
        "generation_sampling": {key: generation.get(key) for key in ("temperature", "top_p", "top_k")},
        "strict_raw_sequence_kl": False,
        "scoring_started_epoch_s": score_started,
        "scoring_finished_epoch_s": score_finished,
        "fixed_bank_sha256": bank_sha,
        "position_chunk_size": int(settings.position_chunk_size),
        "vocab_chunk_size": int(settings.vocab_chunk_size),
        "worker_timings": output.meta_info.get("metrics", {}),
        "metrics": metrics,
        "rows": rows,
        "tokens_sha256": token_digest.hexdigest(),
    }
    with (directory / f"kl-step-{trainer.global_steps}.json").open("x") as stream:
        json.dump(report, stream, indent=2)
        stream.write("\n")
    return rows, metrics
